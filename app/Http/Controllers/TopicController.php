    }

    public function build(Request $request)
    {
        $input = $this->validated($request);

        return view('topic.index', [
            'input' => $input,
            'brief' => $this->makeBrief($input),
        ]);
    }

    public function download(Request $request)
    {
        $input = $this->validated($request);
        $brief = $this->makeBrief($input);

        $file = 'tz-'.\Illuminate\Support\Str::slug($input['project_name']).'.md';

        return response($this->toMarkdown($input, $brief), 200, [
            'Content-Type' => 'text/markdown; charset=UTF-8',
            'Content-Disposition' => 'attachment; filename="'.$file.'"',
        ]);
    }

    private function validated(Request $request): array
    {
        $rules = [];
        foreach (array_keys(self::defaults()) as $key) {
            $rules[$key] = ['required', 'string', 'max:120'];
        }

        return $request->validate($rules, [
            'required' => 'Заполните все поля: без них ТЗ получится неполным.',
        ]);
    }

