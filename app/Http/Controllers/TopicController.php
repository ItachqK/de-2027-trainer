    private function toMarkdown(array $d, array $brief): string
    {
        $out = "# Техническое задание: {$d['project_name']}\n\n";
        $out .= "> Тема вариативная: критерии и структура взяты из КИМ 09.02.07-3-2027, предметную область вы выбираете сами.\n\n";

        $out .= "## 1. Предметная область\n\n";
        foreach ($brief['domain'] as $paragraph) {
            $out .= $paragraph."\n\n";
        }

        $out .= "## 2. Функционал\n\n";
        foreach ($brief['pages'] as $i => $page) {
            $out .= ($i + 1).'. **'.$page['title'].'** — '.$page['text']."\n";
            foreach ($page['rules'] as $rule) {
                $out .= '   - '.$rule."\n";
            }
            $out .= "\n";
        }

        $out .= "## 3. Модель данных\n\n";
        foreach ($brief['tables'] as $table) {
            $out .= '### '.$table['name'].' — '.$table['purpose']."\n\n";
            $out .= "| Поле | Тип | Назначение |\n|---|---|---|\n";
            foreach ($table['fields'] as $field) {
                $out .= '| `'.$field[0].'` | '.$field[1].' | '.$field[2]." |\n";
            }
            $out .= "\n";
        }

        $out .= "## 4. Критерии оценивания (75 баллов, инвариантная часть)\n\n";
        foreach ($brief['criteria'] as $group) {
            $out .= '### '.$group['group']."\n\n";
            foreach ($group['items'] as $item) {
                $out .= '- '.$item[0].' — **'.$item[1]."**\n";
            }
            $out .= "\n";
        }

        $out .= "## 5. Что проверит эксперт\n\n";
        foreach ($brief['checks'] as $check) {
            $out .= '### '.$check['title']."\n\n";
            foreach ($check['items'] as $item) {
                $out .= '- [ ] '.$item."\n";
            }
            $out .= "\n";
        }

        $out .= "## 6. Что менять можно, а что нельзя\n\n";
        $out .= "**Нельзя менять:**\n\n";
        foreach ($brief['invariant'] as $item) {
            $out .= '- '.$item."\n";
        }
        $out .= "\n**Можно менять под свою тему:**\n\n";
        foreach ($brief['variable'] as $item) {
            $out .= '- '.$item."\n";
        }

        return $out;
    }
